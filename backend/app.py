    with get_connection() as connection:
        row = get_user_by_email(connection, payload.email)
        if row is None or row["status"] != "active" or not verify_password(payload.password, row["password_hash"]):
            raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid email or password")
        user = UserOut(
            id=row["id"],
            email=row["email"],
            full_name=row["full_name"],
            role=row["role"],
            status=row["status"],
            created_at=row["created_at"],
            updated_at=row["updated_at"],
            last_login_at=row["last_login_at"],
        )
        if payload.client_type == "admin" and user.role != "admin":
            raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail="Admin account required")
        token, expires_at, csrf_token = create_session(connection, user.id, payload.client_type)
    set_auth_cookie(response, token, expires_at)
    response.set_cookie(
        key="loksewa_csrf",
        value=csrf_token,
        httponly=False,
        secure=settings.environment == "production",
        samesite="strict",
        expires=expires_at,
        path="/",
    )
    return AuthResponse(token=token, user=user, expires_at=expires_at)


