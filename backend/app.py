@app.post("/api/scan")
def api_scan(payload: dict[str, object]) -> dict[str, object]:
    scanned_text = str(
        payload.get("scanned_text")
        or payload.get("text")
        or payload.get("query")
        or ""
    ).strip()
    if len(scanned_text) < 3:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="scanned_text is required")

    result = search(SearchRequest(query=scanned_text, limit=3, allow_ai_fallback=True))
    matched_question_id = result.matches[0].question.id if result.matches else None
    with get_connection() as connection:
        cursor = connection.execute(
            """
            INSERT INTO scan_history (
                scanned_text,
                normalized_scanned_text,
                matched_question_id,
                answer_source
            )
            VALUES (?, ?, ?, ?)
            """,
            (scanned_text, normalize_text(scanned_text), matched_question_id, result.answer_source),
        )
        scan_id = int(cursor.lastrowid)
    return {
        "id": scan_id,
        "status": "completed",
        "result": result.model_dump(mode="json"),
    }


