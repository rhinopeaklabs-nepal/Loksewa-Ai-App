@app.get("/api/flashcards", response_model=list[FlashcardOut])
def api_flashcards(topic: str | None = None, limit: int = Query(default=50, ge=1, le=200)) -> list[FlashcardOut]:
    with get_connection() as connection:
        if topic and topic.isdigit():
            rows = connection.execute(
                "SELECT id, question_id, topic_id, front, back FROM flashcards WHERE topic_id = ? LIMIT ?",
                (int(topic), limit),
            ).fetchall()
        elif topic:
            rows = connection.execute(
                """
                SELECT f.id, f.question_id, f.topic_id, f.front, f.back
                FROM flashcards f
                JOIN topic_notes t ON t.id = f.topic_id
                WHERE t.subject_id = ? OR t.title LIKE ?
                LIMIT ?
                """,
                (topic, f"%{topic}%", limit),
            ).fetchall()
        else:
            rows = connection.execute(
                "SELECT id, question_id, topic_id, front, back FROM flashcards LIMIT ?",
                (limit,),
            ).fetchall()
    return [FlashcardOut(**dict(row)) for row in rows]


