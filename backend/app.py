def ensure_bootstrap_admin(connection) -> None:
    existing_admin = connection.execute(
        "SELECT id FROM app_users WHERE role = 'admin' LIMIT 1"
    ).fetchone()
    if existing_admin is not None:
        return
    connection.execute(
        """
        INSERT INTO app_users (email, password_hash, full_name, role, status)
        VALUES (?, ?, ?, 'admin', 'active')
        """,
        (
            normalize_email(settings.bootstrap_admin_email),
            hash_password(settings.bootstrap_admin_password),
            settings.bootstrap_admin_name,
        ),
    )


def seed_sample_questions(connection) -> None:
    """Auto-seed questions from data/sample_questions.json if table is empty."""
    count_row = connection.execute(
        "SELECT COUNT(*) AS cnt FROM loksewa_questions"
    ).fetchone()
    if int(count_row["cnt"]) > 0:
        return

    sample_path = PROJECT_ROOT / "data" / "sample_questions.json"
    if not sample_path.exists():
        logger.warning("sample_questions.json not found at %s — skipping seed", sample_path)
        return

    with open(sample_path, "r", encoding="utf-8") as fh:
        questions_data = json.load(fh)

    version = int(get_metadata(connection, "data_version", "1"))
    seeded = 0
    for item in questions_data:
        q = QuestionIn(
            question_text=item["question_text"],
            option_a=item["option_a"],
            option_b=item["option_b"],
            option_c=item["option_c"],
            option_d=item["option_d"],
            correct_option=item["correct_option"],
            explanation=item.get("explanation", ""),
            syllabus_category=item.get("syllabus_category", ""),
            source_name=item.get("source_name", "Sample seed data"),
            source_license=item.get("source_license", "Internal sample data"),
            source_year=item.get("source_year"),
            source_page=item.get("source_page"),
            verifier=item.get("verifier", "development_seed"),
            verified_at=item.get("verified_at"),
            verification_status="verified",
        )
        try:
            insert_question(connection, q, data_version=version)
            seeded += 1
        except Exception as exc:
            logger.warning("Failed to seed question: %s", exc)

    logger.info("Seeded %d questions from sample_questions.json", seeded)


