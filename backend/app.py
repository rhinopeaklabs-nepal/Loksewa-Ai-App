@app.post(
    "/v1/admin/import-batch",
    response_model=ImportBatchResponse,
    status_code=status.HTTP_201_CREATED,
    dependencies=[Depends(require_admin_access)],
)
def admin_import_batch(payload: ImportBatchRequest) -> ImportBatchResponse:
    imported_count = 0
    rejected_count = 0

    with get_connection() as connection:
        version = next_data_version(connection)
        cursor = connection.execute(
            """
            INSERT INTO import_batches (
                batch_name,
                source_name,
                source_url,
                source_license,
                verifier
            )
            VALUES (?, ?, ?, ?, ?)
            """,
            (
                payload.batch_name,
                payload.source_name,
                payload.source_url,
                payload.source_license,
                payload.verifier,
            ),
        )
        batch_id = int(cursor.lastrowid)

        for question in payload.questions:
            if not question.source_name:
                question.source_name = payload.source_name
            if not question.source_url:
                question.source_url = payload.source_url
            if not question.source_license:
                question.source_license = payload.source_license
            if not question.verifier:
                question.verifier = payload.verifier
            try:
                insert_question(
                    connection,
                    question,
                    data_version=version,
                    import_batch_id=batch_id,
                )
                imported_count += 1
            except Exception:
                rejected_count += 1

        connection.execute(
            """
            UPDATE import_batches
            SET imported_count = ?, rejected_count = ?
            WHERE id = ?
            """,
            (imported_count, rejected_count, batch_id),
        )

    return ImportBatchResponse(
        batch_id=batch_id,
        imported_count=imported_count,
        rejected_count=rejected_count,
        data_version=version,
    )


