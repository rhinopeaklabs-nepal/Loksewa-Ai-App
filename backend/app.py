@app.post("/v1/search", response_model=SearchResponse)
def search(payload: SearchRequest) -> SearchResponse:
    limit = min(payload.limit, settings.max_search_limit)
    with get_connection() as connection:
        raw_matches = search_questions(connection, payload.query, limit=limit)

    matches = [
        SearchMatch(question=question, bm25_score=bm25_score, similarity=similarity)
        for question, bm25_score, similarity in raw_matches
    ]

    best = matches[0].similarity if matches else 0.0
    if best >= settings.high_confidence_threshold:
        return SearchResponse(
            answer_source="verified_db",
            threshold_reason=f"Best trigram similarity {best:.2f} reached verified threshold.",
            query=payload.query,
            matches=matches,
        )

    if best >= settings.medium_confidence_threshold and payload.allow_ai_fallback:
        return SearchResponse(
            answer_source="ai_assisted",
            threshold_reason=f"Best trigram similarity {best:.2f} reached context threshold.",
            query=payload.query,
            matches=matches,
            disclaimer=AI_DISCLAIMER,
        )

    if payload.allow_ai_fallback:
        return SearchResponse(
            answer_source="ai_only",
            threshold_reason="No verified match passed the context threshold.",
            query=payload.query,
            matches=matches,
            disclaimer=AI_DISCLAIMER,
        )

    return SearchResponse(
        answer_source="uncertain",
        threshold_reason="No verified match and AI fallback is disabled.",
        query=payload.query,
        matches=matches,
    )


