def ensure_bootstrap_admin(connection) -> None:
    existing_admin = connection.execute(
        "SELECT id FROM app_users WHERE role = 'admin' LIMIT 1"
    ).fetchone()
    if existing_admin is not None:
        return
    connection.execute(
        """
        INSERT INTO app_users (email, password_hash, full_name, role, status)
        VALUES (?, ?, ?, 'admin', 'active')
        """,
        (
            normalize_email(settings.bootstrap_admin_email),
            hash_password(settings.bootstrap_admin_password),
            settings.bootstrap_admin_name,
        ),
    )


def seed_sample_questions(connection) -> None:
    """Auto-seed questions from data/sample_questions.json if table is empty."""
    count_row = connection.execute(
        "SELECT COUNT(*) AS cnt FROM loksewa_questions"
    ).fetchone()
    if int(count_row["cnt"]) > 0:
        return

    sample_path = PROJECT_ROOT / "data" / "sample_questions.json"
    if not sample_path.exists():
        logger.warning("sample_questions.json not found at %s — skipping seed", sample_path)
        return

    with open(sample_path, "r", encoding="utf-8") as fh:
        questions_data = json.load(fh)

    version = int(get_metadata(connection, "data_version", "1"))
    seeded = 0
    for item in questions_data:
        q = QuestionIn(
            question_text=item["question_text"],
            option_a=item["option_a"],
            option_b=item["option_b"],
            option_c=item["option_c"],
            option_d=item["option_d"],
            correct_option=item["correct_option"],
            explanation=item.get("explanation", ""),
            syllabus_category=item.get("syllabus_category", ""),
            source_name=item.get("source_name", "Sample seed data"),
            source_license=item.get("source_license", "Internal sample data"),
            source_year=item.get("source_year"),
            source_page=item.get("source_page"),
            verifier=item.get("verifier", "development_seed"),
            verified_at=item.get("verified_at"),
            verification_status="verified",
        )
        try:
            insert_question(connection, q, data_version=version)
            seeded += 1
        except Exception as exc:
            logger.warning("Failed to seed question: %s", exc)

    logger.info("Seeded %d questions from sample_questions.json", seeded)


def ensure_sample_mock_test(connection) -> None:
    """Create 3 diverse mock tests if none exist yet."""
    existing = connection.execute("SELECT id FROM mock_tests LIMIT 1").fetchone()
    if existing is not None:
        return

    mock_definitions = [
        {
            "title": "Constitution & Governance Practice",
            "description": "Focused practice on Constitution and Governance topics.",
            "categories": ["Constitution", "Governance"],
            "question_count": 20,
            "duration_minutes": 30,
        },
        {
            "title": "General Knowledge Mixed Set",
            "description": "Mixed practice covering General Knowledge, Geography, and History.",
            "categories": ["General Knowledge", "Geography", "History"],
            "question_count": 25,
            "duration_minutes": 45,
        },
        {
            "title": "Full Loksewa Practice Exam",
            "description": "Comprehensive practice exam covering all categories.",
            "categories": [],  # all categories
            "question_count": 50,
            "duration_minutes": 60,
        },
    ]

    for defn in mock_definitions:
        if defn["categories"]:
            placeholders = ", ".join("?" for _ in defn["categories"])
            rows = connection.execute(
                f"""
                SELECT id
                FROM loksewa_questions
                WHERE verification_status = 'verified'
                  AND syllabus_category IN ({placeholders})
                ORDER BY id ASC
                LIMIT ?
                """,
                (*defn["categories"], defn["question_count"]),
            ).fetchall()
        else:
            rows = connection.execute(
                """
                SELECT id
                FROM loksewa_questions
                WHERE verification_status = 'verified'
                ORDER BY id ASC
                LIMIT ?
                """,
                (defn["question_count"],),
            ).fetchall()

        if not rows:
            logger.info(
                "Skipping mock test '%s': not enough verified questions",
                defn["title"],
            )
            continue

        mock = MockTestIn(
            title=defn["title"],
            description=defn["description"],
            exam_level="General",
            exam_type="MCQ",
            syllabus_category=", ".join(defn["categories"]) if defn["categories"] else "Mixed",
            duration_minutes=defn["duration_minutes"],
            marks_per_correct=1.0,
            negative_marking_enabled=True,
            negative_marks_per_wrong=0.2,
            status="published",
            question_ids=[int(row["id"]) for row in rows],
        )
        create_mock_test(connection, mock, created_by=None)
        logger.info(
            "Created mock test '%s' with %d questions",
            defn["title"],
            len(rows),
        )


